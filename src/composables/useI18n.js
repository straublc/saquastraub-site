const locale = ref(localStorage.getItem('lang') || 'pt')

export function useI18n() {
  const t = (key) => {
    return TRANSLATIONS[locale.value]?.[key] ?? TRANSLATIONS.pt[key] ?? key
  }

  const setLang = (lang) => {
    if (TRANSLATIONS[lang]) {
      locale.value = lang
      localStorage.setItem('lang', lang)
      document.documentElement.lang =
        lang === 'pt' ? 'pt-BR' :
        lang === 'fr' ? 'fr-FR' :
        lang === 'it' ? 'it-IT' :
        lang === 'de' ? 'de-DE' :
        lang
    }
  }

  return { t, locale, setLang }
}
